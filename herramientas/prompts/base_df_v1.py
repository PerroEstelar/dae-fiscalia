def arma(escena, registro='dia', personas=(), con_acento=False,
         con_lugar=True, con_rostro=True, exterior=False, silueta=False):
    """Arma el prompt final. Lo armado es lo que se manda y lo que se guarda.

    `silueta=True` reemplaza el bloque de rostro y de piel por la clausula
    de silueta: no hay cara que describir porque no debe haberla.
    """
    p = [escena.strip()]
    if personas:
        p.append('WHO THESE PEOPLE ARE. ' + ' '.join(VIDA[x] for x in personas
                                                     if x in VIDA))
    p.append(REGISTRO[registro])
    p.append(PLANOS)
    if silueta:
        p.append(ESTILO + FIGURA)
        p.append(SILUETA)
    else:
        p.append(ESTILO + (ROSTRO if (con_rostro and personas) else '')
                 + (PIEL + ' ' if personas else '') + FIGURA)
    p.append(CAMARA)
    if con_acento:
        p.append(ACENTO)
    if con_lugar:
        p.append(EXTERIOR if exterior else LUGAR)
    p.append(LIMPIA)
    p.append(SIN_ROLES)
    p.append(NEG)
    return '\n\n'.join(x.strip() for x in p if x and x.strip())
